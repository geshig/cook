-- Пусни веднъж в Supabase → SQL Editor. Ако я пуснеш пак, няма да се дублира.
do $$
declare v_id bigint;
begin
  if not exists (select 1 from recipes where title = 'Паста със скариди, спанак и сушени домати') then
    insert into recipes (title, time_minutes, servings, kcal, protein_g, carbs_g, fat_g, ingredients, steps, video_url, photo_url, is_locked, batch_number)
    values ('Паста със скариди, спанак и сушени домати', 25, 4, 560, 48, 65, 13,
      '320 g пълнозърнести спагети; 600 g обелени скариди (размразени); 150 g light крема сирене; 300 g чери домати (на половинки); 40 g сушени домати (отцедени и нарязани); 100 g бейби спанак; 4 скилидки чесън (ситно нарязан); 30 g пармезан (настърган); 1 с.л. зехтин; 120 ml вода от пастата; сол и черен пипер; щипка люти люспи (по желание)',
      E'1. Свари спагетите според опаковката. Запази 120 ml от водата и ги отцеди.\n2. Подсуши скаридите с хартия и ги овкуси със сол, пипер и люти люспи. Запържи ги в зехтина по 1–2 мин от всяка страна, докато порозовеят, и ги извади.\n3. В същия тиган сложи чесъна, чери доматите и сушените домати и готви 3–4 мин, докато доматите омекнат.\n4. Добави крема сиренето и водата от пастата и разбъркай до гладък сос. Сложи спанака и разбъркай, докато омекне.\n5. Върни скаридите и спагетите, разбъркай и поръсни с пармезан.\n6. Съвет: скаридите не ги препържвай, иначе стават гумени. Изключи котлона, щом порозовеят.\n7. Съвет: за кутии за работа сложи пармезана чак преди ядене.',
      NULL, '/recipes/pasta-skaridi.jpg', true, 1)
    returning id into v_id;
    insert into recipe_tags (recipe_id, tag_id)
      select v_id, id from tags where name in ('риба', 'обяд', 'вечеря', 'high-protein', 'балансирано', 'на тиган', 'meal prep');
  end if;
end $$;

