-- Текстовете са чернова: „Къде го купувам“ попълваш от /admin/produkti.
create table if not exists products (
  id bigint generated always as identity primary key,
  name text not null,
  body text,
  where_to_buy text,
  link text,
  photo_url text,
  sort int default 0,
  created_at timestamptz default now()
);
alter table products enable row level security;

insert into products (name, body, sort)
select * from (values
  ($$Обезмаслено гръцко кисело мляко или скир$$, $$Най-честият продукт в книгата, в над 40 рецепти. От него правя леките сосове, дресингите и мариновките вместо майонеза и сметана. Гъсто е, дава много протеин и почти няма мазнина.$$, 1),
  ($$Котидж чийз$$, $$В 24 рецепти: тесто за пица, брауни, сосове, закуски. Пасиран става гладък като крем и вдига протеина, без вкусът да се усеща. Взимам нискомаслен.$$, 2),
  ($$Лека майонеза$$, $$Ползвам я в малко количество за соса и вкуса, обикновено смесена с кисело мляко. Има около половината калории на класическата.$$, 3),
  ($$Light крема сирене$$, $$Прави сосовете за паста кремообразни и е основата на чийзкейк десертите. Light версията има много по-малко мазнини от обикновената.$$, 4),
  ($$Протеин на прах (ванилов и шоколадов)$$, $$За десертите, протеиновия овес и кейка в чаша. Вкусът на протеина се усеща в крайния резултат, затова избирам такъв, който ми харесва и сам.$$, 5),
  ($$Light моцарела и протеинов кашкавал$$, $$За пиците, калцонето и запечените ястия. Топят се като нормалните, но с повече протеин и по-малко мазнини.$$, 6),
  ($$Протеинови или пълнозърнести тортили$$, $$За буритата, рулцата, тостадас и киша с тортиля. Гледам да са с повече протеин и фибри.$$, 7),
  ($$Еритритол или стевия$$, $$Подсладител без калории за десертите и сосовете, вместо захар. Еритритолът се ползва почти 1 към 1 като захар, стевията е много по-сладка и се слага съвсем малко.$$, 8)
) as v(name, body, sort)
where not exists (select 1 from products);
