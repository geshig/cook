-- ---------------------------------------------------------------------
-- 2) Лийд магнит списък — пише имейл формата на landing страницата.
--    Отделно от subscribers: тук няма плащане, само записан интерес.
-- ---------------------------------------------------------------------

create table if not exists leads (
  id bigint generated always as identity primary key,
  email text unique not null,
  source text default 'landing',
  created_at timestamptz default now()
);

-- ---------------------------------------------------------------------
-- 3) Row Level Security — default-deny.
--    Нито anon, нито authenticated роля имат директен достъп през
--    Supabase API до тези таблици — умишлено няма policy-та по-долу.
--    Единственият път за четене/писане е service_role ключът, който
--    се използва само в сървърен код (Next.js API routes / server
--    components), никога в браузъра. Точно това пази заключеното
--    съдържание (текст, видео линк) от непроверени потребители —
--    дори някой да намери anon ключа, таблиците са невидими за него.
-- ---------------------------------------------------------------------

alter table recipes enable row level security;
alter table tags enable row level security;
alter table recipe_tags enable row level security;
alter table subscribers enable row level security;
alter table leads enable row level security;
